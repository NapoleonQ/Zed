# Practica de Sentencias Condicionales Compuestas:

"""Primero un ejemplo de como es la estructura:
    If (Condicion Logica):
        (Instruccion)
    Else:
        (Instruccion si no se cumple la condicion logica)"""

# Test siguiendo el ejemplo

num = int(input("Ingrese el numero (5): "))

if num == 5:
    print("Es correcto, el numero es 5")
else:
    print("Incorrecto, el numero no es 5")

print("Fin.")
