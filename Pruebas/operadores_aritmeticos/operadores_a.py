# Operadores Aritmeticos en Python

# Sumatoria
num1 = 2
num2 = 2
resul = num1 + num2

print("==Suma==")
print("El resultado de la sumatoria es: " + str(resul))
print()

# Resta
num1 = 3
num2 = 2
resul = num1 - num2

print("==Resta==")
print("El resultado de la resta es: " + str(resul))
print()

# Multiplicacion
num1 = 3
num2 = 4
resul = num1 * num2

print("==Multiplicacion==")
print("El resultado de la multiplicacion es: " + str(resul))
print()

# Division
num1 = 4
num2 = 2
