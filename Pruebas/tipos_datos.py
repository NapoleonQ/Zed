# Tipos de Datos: int (Enteros) y long (Largos)

num = 12
print(num, type(num))

# Tipos de Datos: float (Flotantes)

num_float = 23.2
print(num_float, type(num_float))

# Tipos de Datos: Complex (Complejos)

num_complex = 5 + 6j
print(num_complex, type(num_complex))

# Tipos de Datos: Strings (Cadena de Texto)

nombre = "Napoleon"
print(nombre, type(nombre))

# Tipos de Datos: Boolean (Booleano)

verdadero_falso = 3 == 3
print(verdadero_falso, type(verdadero_falso))
